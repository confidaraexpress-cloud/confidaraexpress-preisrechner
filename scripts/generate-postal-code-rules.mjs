#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// Deterministic generator: src/utils/address-metadata.json
//                          →  src/utils/generated/postalCodeRules.mjs
//
// The canonical snapshot (src/utils/address-metadata.json) is the SINGLE source of
// truth for country-specific postal-code rules. This script reads it, validates
// every rule (pattern compiles, documented example passes its own rule, no
// duplicate ISO codes), and emits a frozen ESM rules module for the browser bundle.
//
// Deterministic: same snapshot in → byte-identical output. Exits non-zero on any
// validation failure so the build/test gate catches drift. Only postal-code fields
// are emitted — no region/subregion metadata is pulled into the frontend bundle.
//
// Run:  node scripts/generate-postal-code-rules.mjs
//       node scripts/generate-postal-code-rules.mjs --check   (verify only, no write)
//
// The backend repo carries an identical snapshot + an equivalent .js generator;
// both generated artifacts originate from the same canonical data and share the
// same `version`.
// ─────────────────────────────────────────────────────────────────────────────
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SNAPSHOT = path.join(__dirname, "..", "src", "utils", "address-metadata.json");
const OUT = path.join(__dirname, "..", "src", "utils", "generated", "postalCodeRules.mjs");

function build() {
  const meta = JSON.parse(fs.readFileSync(SNAPSHOT, "utf8"));
  const countries = meta.countries || {};
  const codes = Object.keys(countries);

  const errors = [];
  const seen = new Set();
  for (const cc of codes) {
    if (!/^[A-Z]{2}$/.test(cc)) errors.push(`invalid ISO code: ${cc}`);
    if (seen.has(cc)) errors.push(`duplicate ISO code: ${cc}`);
    seen.add(cc);
    const r = countries[cc] || {};
    if (typeof r.postalCodeRequired !== "boolean") errors.push(`${cc}: postalCodeRequired must be boolean`);
    if (r.postalCodePattern != null) {
      let re;
      try { re = new RegExp("^(?:" + r.postalCodePattern + ")$", "i"); }
      catch (e) { errors.push(`${cc}: pattern does not compile: ${e.message}`); continue; }
      if (r.postalCodeExample != null) {
        const ex = r.postalCodeUppercase ? String(r.postalCodeExample).toUpperCase() : String(r.postalCodeExample);
        if (!re.test(ex)) errors.push(`${cc}: documented example "${r.postalCodeExample}" fails its own rule`);
      }
    } else if (r.postalCodeRequired === true) {
      errors.push(`${cc}: postalCodeRequired=true but no pattern`);
    }
  }
  if (errors.length) {
    console.error("[generate-postal-code-rules] snapshot validation FAILED:\n  - " + errors.join("\n  - "));
    process.exit(1);
  }

  const rules = {};
  for (const cc of codes) {
    const r = countries[cc];
    rules[cc] = {
      required: r.postalCodeRequired === true,
      pattern: r.postalCodePattern == null ? null : String(r.postalCodePattern),
      example: r.postalCodeExample == null ? null : String(r.postalCodeExample),
      uppercase: r.postalCodeUppercase === true,
    };
  }

  // Semantischer Hash NUR über die kanonischen Regeln — identisch zum Backend, solange die
  // Regeln gleich sind (ohne version/source/Repo-spezifische Felder).
  const rulesSha256 = crypto.createHash("sha256").update(JSON.stringify(rules)).digest("hex");

  const body =
`// AUTO-GENERATED by scripts/generate-postal-code-rules.mjs — DO NOT EDIT BY HAND.
// Source: src/utils/address-metadata.json (${meta.source}), snapshot version ${meta.version}.
// Regenerate after any snapshot change:  node scripts/generate-postal-code-rules.mjs
export const version = ${JSON.stringify(meta.version)};
export const source = ${JSON.stringify(meta.source)};
export const rulesSha256 = ${JSON.stringify(rulesSha256)};
export const rules = Object.freeze(${JSON.stringify(rules, null, 2)});
`;
  return { body, count: codes.length, version: meta.version };
}

const checkOnly = process.argv.includes("--check");
const { body, count, version } = build();
if (checkOnly) {
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (existing !== body) {
    console.error("[generate-postal-code-rules] --check: generated output is STALE. Run the generator.");
    process.exit(1);
  }
  console.log(`[generate-postal-code-rules] --check OK (${count} countries, version ${version})`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);
  console.log(`[generate-postal-code-rules] wrote src/utils/generated/postalCodeRules.mjs (${count} countries, version ${version})`);
}
